#!/usr/bin/env nix-shell
#!nix-shell -i bash -p cargo rustc git nix-prefetch-git python3 cacert nix coreutils
#
# Regenerate nix/edenfs/Cargo.lock and output-hashes.nix for the Sapling
# snapshot pinned in package.nix.
#
# Usage (from anywhere in the repo):
#   ./nix/edenfs/update.sh
#
# Keep SNAPSHOT_REV in sync with `saplingSrc`'s `rev` in package.nix.
# The eden/fs Cargo.toml pulls several git crates behind `branch = "main"`,
# so a regenerated lock captures whatever those branches point at *right now*;
# bump the revs in eden/fs/Cargo.toml if you need to freeze them.

set -euo pipefail

SNAPSHOT_REV="3b4d56d3be392d9df1f55d05aed448b542a18d5d"

repo_root="$(git rev-parse --show-toplevel)"
pkg_dir="$repo_root/nix/edenfs"

tmpdir="$(mktemp -d)"
trap 'rm -rf "$tmpdir"' EXIT

echo "==> Fetching Sapling $SNAPSHOT_REV"
mapfile -t prefetch < <(
  nix-prefetch-url --unpack --print-path \
    "https://github.com/meta/sapling/archive/$SNAPSHOT_REV.tar.gz"
)
src_dir="${prefetch[1]}"
cp -r "$src_dir" "$tmpdir/src"
chmod -R u+w "$tmpdir/src"

fs_dir="$tmpdir/src/eden/fs"

echo "==> Generating Cargo.lock"
(
  cd "$fs_dir"
  cargo generate-lockfile
)

# cargo records every `[patch]` entry that ended up unused as `[[patch.unused]]`.
# The build drops those patches (trim-patches.py), so clean them out of the lock
# too.  The manifest is restored afterwards.
manifest="$fs_dir/Cargo.toml"
cp "$manifest" "$manifest.edenfs-nix-backup"
trap 'rm -rf "$tmpdir"' EXIT
python3 "$pkg_dir/trim-patches.py" "$manifest" "$fs_dir/Cargo.lock"
(
  cd "$fs_dir"
  cargo metadata --format-version 1 > /dev/null
)
mv -f "$manifest.edenfs-nix-backup" "$manifest"

cp "$fs_dir/Cargo.lock" "$pkg_dir/Cargo.lock"
echo "==> Copied Cargo.lock ($(grep -c '^\[\[package\]\]' "$pkg_dir/Cargo.lock") packages)"

echo "==> Prefetching git dependencies and writing output-hashes.nix"
python3 - "$pkg_dir/Cargo.lock" "$pkg_dir/output-hashes.nix" <<'PY'
import json
import subprocess
import sys
import tomllib
from collections import defaultdict

lock_path, out_path = sys.argv[1], sys.argv[2]

with open(lock_path, "rb") as f:
    lock = tomllib.load(f)

# Group packages by git repo/rev so each repo is only prefetched once.
by_rev = defaultdict(list)
for pkg in lock.get("package", []):
    source = pkg.get("source", "")
    if not source.startswith("git+"):
        continue
    parts = source.split("#")
    if len(parts) != 2:
        continue
    rev = parts[1]
    url = parts[0][4:].split("?")[0]
    by_rev[(url, rev)].append(f'{pkg["name"]}-{pkg["version"]}')

lines = [
    "# Generated by ./update.sh -- do not edit by hand.",
    "{",
]
for (url, rev), names in sorted(by_rev.items()):
    out = subprocess.check_output(
        [
            "nix-prefetch-git",
            "--url",
            url,
            "--rev",
            rev,
            # importCargoLock's fetchgit defaults to fetchSubmodules = true,
            # so the prefetched hash must include submodules too.
            "--fetch-submodules",
            "--quiet",
        ],
        text=True,
    )
    h = json.loads(out)["hash"]
    for name in sorted(names):
        lines.append(f'      "{name}" = "{h}";')
lines.append("}")

with open(out_path, "w") as f:
    f.write("\n".join(lines) + "\n")

print(f"==> Wrote {out_path} ({sum(len(v) for v in by_rev.values())} git packages)")
PY

echo "==> Done."
