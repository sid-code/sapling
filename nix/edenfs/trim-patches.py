#!/usr/bin/env python3
"""Drop `[patch]` git entries that the lock file says are unused.

`eden/fs/Cargo.toml` is generated by autocargo and lists ~100 `[patch]`
entries for every dependency any Meta target might use.  When building this
one workspace most of them are unused, but cargo still tries to *load* every
patch's git source during resolution -- which fails in the Nix sandbox (no
network).  Removing the unused entries lets cargo resolve fully offline.

Usage: trim-patches.py <Cargo.toml> <Cargo.lock>
"""

import sys
import tomllib


def used_git_names(lock_path):
    with open(lock_path, "rb") as f:
        lock = tomllib.load(f)
    return {
        pkg["name"]
        for pkg in lock.get("package", [])
        if pkg.get("source", "").startswith("git+")
    }


def trim(manifest_path, lock_path):
    used = used_git_names(lock_path)
    lines = open(manifest_path).read().splitlines(keepends=True)

    out = []
    in_patch = False
    dropped = 0
    for line in lines:
        stripped = line.strip()
        if stripped.startswith("["):
            in_patch = stripped.startswith("[patch")
            out.append(line)
            continue

        if in_patch and stripped and not stripped.startswith("#") and "=" in stripped:
            if "git = " in stripped:
                name = stripped.split("=", 1)[0].strip()
                if "package = " in stripped:
                    name = stripped.split("package = ", 1)[1].split('"')[1]
                if name not in used:
                    dropped += 1
                    continue
        out.append(line)

    open(manifest_path, "w").write("".join(out))
    print(f"trim-patches: dropped {dropped} unused git patch entries", file=sys.stderr)


if __name__ == "__main__":
    trim(sys.argv[1], sys.argv[2])
